#!/usr/bin/env python3
"""
post-approve hook - runs after pm-approve completes.

1. Cascade staleness: downstream approved stages -> stale. pm_approve.py has
   already done this in the same write as the approval (backlog #31/#57), so
   here it is an idempotent safety net that normally finds nothing to demote.
2. Render companion HTML for stages 04 and 05.
3. Rebuild the traceability index, commit the project locally, and sync telemetry + feedback JSONL to feedback repo (deferred by default).
"""

import subprocess
import sys
import os
from pathlib import Path

import yaml

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "lib"))

from console import ensure_utf8_stdio  # noqa: E402
ensure_utf8_stdio()

from project import resolve_project, load_meta, save_meta, get_stage
from cascade import cascade_stale
from html_render import render_design_spec, render_prototype_mockup
from telemetry import log
from git_sync import push_feedback_repo


def _truthy(value) -> bool:
    return str(value or "").strip().lower() in {"1", "true", "yes", "on"}


def _active_enhancement_surfaces(project_root):
    """Return active E2 surfaces, or None when this is not an E2 cycle."""
    index_path = Path(project_root) / ".enhancements" / "index.yaml"
    if not index_path.exists():
        return None
    try:
        index = yaml.safe_load(index_path.read_text(encoding="utf-8")) or {}
        cycle_id = index.get("active_cycle")
        if not cycle_id:
            return None
        context_path = Path(project_root) / ".enhancements" / cycle_id / "context.yaml"
        context = yaml.safe_load(context_path.read_text(encoding="utf-8")) or {}
        surfaces = (context.get("boundary") or {}).get("affected_surfaces") or []
        return {str(surface).strip().lower() for surface in surfaces if str(surface).strip()}
    except (OSError, yaml.YAMLError, AttributeError):
        return None


def _spawn_background_sync(project_root) -> None:
    """Fire the central feedback-repo push as a detached background process.

    A network push must never gate the PM's perceived approval completion
    (backlog #6). The approval state is already durably written locally by the
    time we get here; the push only propagates it to the central repo, and
    /pm-sync is the catch-up + retry path. Output goes to a per-project log so a
    background failure is inspectable rather than lost.
    """
    lib_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "lib"))
    child_env = os.environ.copy()
    child_env["PM_OS_LIB_PATH"] = lib_dir
    child_env["PM_OS_SYNC_PROJECT"] = str(project_root)
    code = (
        "import os, sys; from pathlib import Path; "
        "sys.path.insert(0, os.environ['PM_OS_LIB_PATH']); "
        "from git_sync import push_feedback_repo; "
        "push_feedback_repo(Path(os.environ['PM_OS_SYNC_PROJECT']))"
    )
    log_path = os.path.join(str(project_root), ".pm-os-sync.log")
    logf = open(log_path, "ab")
    subprocess.Popen(
        [sys.executable, "-c", code],
        stdout=logf, stderr=logf, stdin=subprocess.DEVNULL,
        start_new_session=True, cwd=str(project_root), env=child_env,
    )


def main():
    stage_id = os.environ.get("PM_OS_STAGE")
    if not stage_id:
        sys.exit(0)

    try:
        project_root = resolve_project()
    except FileNotFoundError as e:
        print(f"[post-approve] ERROR: {e}", file=sys.stderr)
        sys.exit(1)

    meta = load_meta(project_root)

    # --- Cascade staleness to downstream approved stages (first: cheapest, most important) ---
    stale_logged = cascade_stale(
        meta, project_root, [stage_id],
        {"reason": "upstream_approved", "triggering_upstream_stage": stage_id},
    )
    if stale_logged:
        save_meta(meta, project_root)
        print(f"[post-approve] Marked downstream stages stale: {', '.join(stale_logged)}")

    # --- Render companion HTML for stages with generated previews ---
    # E2 non-UI work uses surface-appropriate validation artifacts; it must not
    # acquire fabricated design/prototype HTML merely because stages 04/05 were approved.
    enhancement_surfaces = _active_enhancement_surfaces(project_root)
    try:
        if stage_id in {"04", "05"} and enhancement_surfaces is not None and "ui" not in enhancement_surfaces:
            print(f"[post-approve] Skipped HTML render: non-UI enhancement surfaces "
                  f"({', '.join(sorted(enhancement_surfaces)) or 'not declared'}).")
        elif stage_id == "04":
            output_path = render_design_spec(project_root)
            print(f"[post-approve] Rendered companion HTML: {output_path.name}")
        elif stage_id == "05":
            mockup_path = project_root / "05-prototype-mockup.html"
            if mockup_path.exists():
                print(f"[post-approve] Skipped HTML render: 05-prototype-mockup.html already present (generated by pm-prototype-html skill).")
            else:
                output_path = render_prototype_mockup(project_root)
                print(f"[post-approve] Rendered fallback companion HTML: {output_path.name}")
    except Exception as e:
        print(f"[post-approve] WARNING: Could not render companion HTML: {e}", file=sys.stderr)

    # --- Rebuild the traceability spine when an ID-bearing stage is approved ---
    # Stage 03 (PRD) declares requirement ids; stage 04 (design spec) declares the
    # SCR-### screens that serve them; stage 06 (QA plan) declares the TC-### scenarios
    # that link to them; stage 08 (TRD) declares the TSK-### Work Breakdown tasks that
    # implement them. Re-derive .traceability.yaml (a local, derived index) so the
    # resolver answers coverage/handoff queries without rescanning.
    if stage_id in {"03", "04", "06", "08"}:
        try:
            import traceability as trace
            index = trace.rebuild(project_root)
            reqs = len(index.get("requirements") or {})
            tcs = len(index.get("test_cases") or {})
            tasks = len(index.get("tasks") or {})
            screens = len(index.get("screens") or {})
            print(f"[post-approve] Rebuilt {trace.TRACEABILITY_FILENAME}: "
                  f"{reqs} requirement(s), {tcs} test case(s), {tasks} task(s), "
                  f"{screens} screen(s).")
            uncovered = trace.uncovered_requirements(project_root)
            if uncovered:
                print(f"[post-approve] Requirements with no covering scenario: "
                      f"{', '.join(uncovered)}")
        except Exception as e:
            print(f"[post-approve] WARNING: Could not rebuild traceability: {e}",
                  file=sys.stderr)

    # --- Commit the project to its local git repo (backlog #18) ---
    # The project's OWN version history, entirely separate from the central
    # feedback-repo sync below. The approval is already durably written to disk
    # at this point; this just snapshots it so it is diffable and recoverable.
    # Warn-not-fail: a git problem must never gate approval.
    try:
        from project_git import commit_all
        pm_user = "pm-os"
        try:
            from config import load_config
            pm_user = load_config().get("pm_user") or "pm-os"
        except Exception:
            pass
        try:
            stage_name = get_stage(meta, stage_id).get("name", stage_id)
        except KeyError:
            stage_name = stage_id
        vcs = commit_all(project_root, f"approve: stage {stage_id} {stage_name}", pm_user=pm_user)
        if vcs.get("ok"):
            if vcs.get("reason") == "committed":
                print(f"[post-approve] Versioned project locally (git): stage {stage_id}.")
            left_out = vcs.get("untracked_left_out") or []
            if left_out:
                shown = ", ".join(left_out[:5]) + (f" (+{len(left_out) - 5} more)" if len(left_out) > 5 else "")
                print(f"[post-approve] Not committed (not PM-OS files): {shown}. "
                      "Commit them yourself if you want them versioned.")
        else:
            print(f"[post-approve] WARNING: local git commit skipped — {vcs.get('reason')}",
                  file=sys.stderr)
    except Exception as e:
        print(f"[post-approve] WARNING: could not commit to local git: {e}", file=sys.stderr)

    # --- Sync to feedback repo ---
    # By default this is DEFERRED to a detached background process so the
    # network push never gates the PM's perceived approval completion (backlog
    # #6). The approval is already saved locally at this point. Set
    # PM_OS_SYNC_BLOCKING=1 (CI/tests, or a PM who wants a synchronous confirm)
    # to push inline and report status. Either way, /pm-sync is the catch-up path.
    if _truthy(os.environ.get("PM_OS_SYNC_BLOCKING")):
        try:
            status = push_feedback_repo(project_root)
            if status.get("ok"):
                print(f"[post-approve] Central sync: {status.get('reason')}.")
            else:
                print(f"[post-approve] Central sync FAILED — {status.get('reason')}. "
                      f"Retry with /pm-sync.", file=sys.stderr)
        except Exception as e:
            print(f"[post-approve] WARNING: Could not push to feedback repo: {e}", file=sys.stderr)
    else:
        try:
            _spawn_background_sync(project_root)
            print("[post-approve] Central sync started in the background — your approval "
                  "is already saved locally. Run /pm-sync to verify or retry it.")
        except Exception as e:
            print(f"[post-approve] WARNING: Could not start background sync: {e}. "
                  f"Run /pm-sync to push manually.", file=sys.stderr)

    sys.exit(0)


if __name__ == "__main__":
    main()
